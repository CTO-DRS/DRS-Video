  /// Latin-1: bytes 0x80..0xFF map to U+0080..U+00FF directly.
  static String _decodeLatin1(List<int> bytes) =>
      String.fromCharCodes(bytes);

  /// Decodes a single-byte-charset payload via [table] (0x00..0x7F are
  /// ASCII in all of them). Undefined bytes become U+FFFD.
  static String _decodeHigh(List<int> bytes, List<int> table) {
    // NOTE: StringBuffer's constructor takes initial CONTENT, not a
    // capacity — never pass the byte count there.
    final out = StringBuffer();
    for (final b in bytes) {
      if (b < 0x80) {
        out.writeCharCode(b);
      } else {
        final cp = table[b - 0x80];
        out.writeCharCode(cp == 0 ? 0xFFFD : cp);
      }
    }
    return out.toString();
  }

  // ---- detection ---------------------------------------------------------

  /// UTF-8 BOM.
  static const List<int> _bom = [0xEF, 0xBB, 0xBF];

  static bool _hasUtf8Bom(List<int> b) =>
      b.length >= 3 && b[0] == _bom[0] && b[1] == _bom[1] && b[2] == _bom[2];

  /// Strict UTF-8 validation (no BOM needed). Dart's utf8.decode throws
  /// on invalid input, which is exactly the strictness detection needs.
  static bool _isStrictUtf8(List<int> bytes) {
    try {
      utf8.decode(bytes);
      return true;
    } on FormatException {
      return false;
    }
  }

  /// True when [ch] is an Arabic-block letter (incl. Tatweel/punct that
  /// only occur in Arabic text).
  static bool isArabicChar(int ch) =>
      (ch >= 0x0600 && ch <= 0x06FF) ||
      (ch >= 0x0750 && ch <= 0x077F) ||
      (ch >= 0xFB50 && ch <= 0xFDFF) ||
      (ch >= 0xFE70 && ch <= 0xFEFF);

