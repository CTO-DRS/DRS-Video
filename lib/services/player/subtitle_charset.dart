import 'dart:convert';
import 'dart:typed_data';

/// Subtitle text encodings (v1.10.0 Arabic toolkit).
///
/// Legacy Arabic subtitle files (.srt from old sites) are almost always
/// Windows-1256 or ISO-8859-6 — decoded as raw bytes by mpv they show up
/// as mojibake (Ø£Ø­Ù…Ø¯ or ¿¿¿). Dart ships no single-byte Arabic codec,
/// so the tables below (generated from the WHATWG/IANA mappings) do the
/// conversion natively, plus a scoring heuristic that picks the right one
/// automatically.
enum SubtitleEncoding {
  auto('auto'),
  utf8('utf8'),
  windows1256('windows1256'),
  iso8859_6('iso8859_6'),
  windows1252('windows1252');

  const SubtitleEncoding(this.id);

  /// Stable persistence/UI token.
  final String id;

  static SubtitleEncoding fromId(String? id) => SubtitleEncoding.values
      .firstWhere((e) => e.id == id, orElse: () => SubtitleEncoding.auto);
}

