  /// Mean frequency weight of the Arabic letters in [text], minus a
  /// penalty for replacement characters. 0 when there are no Arabic
  /// letters (Latin candidates therefore never win by accident).
  static double _scoreArabic(String text) {
    var arabic = 0;
    var weight = 0.0;
    var bad = 0;
    for (final r in text.runes) {
      if (r == 0xFFFD) {
        bad++;
        continue;
      }
      final w = _letterWeight[r];
      if (w != null) {
        arabic++;
        weight += w;
      }
    }
    if (arabic == 0) return 0;
    final mean = weight / arabic;
    final badRatio = bad / (bad + arabic);
    return mean - badRatio * 10;
  }

  /// Picks the encoding for [bytes]:
  /// 1. UTF-8 BOM or strict-valid UTF-8 → utf8 (superset: any ASCII file
  ///    also validates, which is correct — ASCII is the same everywhere).
  /// 2. Otherwise decode with the three candidate charsets and score each
  ///    by MEAN ARABIC LETTER FREQUENCY (see [_letterWeight]): the correct
  ///    charset turns the text into common letters, while the wrong Arabic
  ///    charset maps common letters onto rare ones. Replacement characters
  ///    (bytes undefined in a candidate) are penalized per occurrence.
  ///    Pure Latin text scores 0 on every candidate → windows1252.
  ///    Never throws.
  static SubtitleEncoding detect(List<int> bytes) {
    final b = bytes is Uint8List ? bytes : Uint8List.fromList(bytes);
    if (b.isEmpty) return SubtitleEncoding.utf8;
    if (_hasUtf8Bom(b)) return SubtitleEncoding.utf8;
    if (_isStrictUtf8(b)) return SubtitleEncoding.utf8;

    final s1256 = _scoreArabic(_decodeHigh(b, _cp1256High));
    final sIso = _scoreArabic(_decodeHigh(b, _iso8859_6High));
    final sLatin = _scoreArabic(_decodeLatin1(b));

    if (s1256 < _arabicThreshold &&
        sIso < _arabicThreshold &&
        sLatin < _arabicThreshold) {
      // No candidate looks like real Arabic prose → legacy Latin text.
      return SubtitleEncoding.windows1252;
    }
    // windows-1256 is overwhelmingly the most common encoding for legacy
    // Arabic .srt files, so ties go to it.
    if (s1256 >= sIso && s1256 >= sLatin) return SubtitleEncoding.windows1256;
    if (sIso >= sLatin) return SubtitleEncoding.iso8859_6;
    return SubtitleEncoding.windows1252;
  }

  /// Real Arabic prose scores ~6-7.5 on the frequency scale; stray accented
  /// Latin letters misread through an Arabic table peak around ~1.0. The
  /// midpoint is a safe cut.
  static const double _arabicThreshold = 2.5;

  /// Decodes subtitle bytes with an explicit or auto-detected encoding.
  /// Never throws: undecodable input degrades to replacement characters.
  static String decode(List<int> bytes, {SubtitleEncoding? encoding}) {
    final enc = encoding ?? SubtitleEncoding.auto;
    final b = bytes is Uint8List ? bytes : Uint8List.fromList(bytes);
    switch (enc) {
      case SubtitleEncoding.utf8:
        return utf8.decode(b, allowMalformed: true);
      case SubtitleEncoding.windows1256:
        return _decodeHigh(b, _cp1256High);
      case SubtitleEncoding.iso8859_6:
        return _decodeHigh(b, _iso8859_6High);
      case SubtitleEncoding.windows1252:
        return _decodeLatin1(b);
      case SubtitleEncoding.auto:
        final detected = detect(b);
        if (detected == SubtitleEncoding.auto) {
          return utf8.decode(b, allowMalformed: true);
        }
        return decode(b, encoding: detected);
    }
  }
}
